#!/usr/bin/env bash
set -euo pipefail

usage='Usage: swg.sh {install|update} {panel|node} [--dry-run]
       swg.sh install node --panel-url URL --token-stdin [--node-endpoint HOST] [--revision SHA] [--dry-run]
       swg.sh update node [--revision SHA] [--dry-run]'
settings_header='# Generated by swg.sh'
source_repo=https://github.com/tesla-prep/vpn-panel.git

die() {
    printf 'Error: %s\n' "$*" >&2
    exit 1
}

valid_port() {
    [[ $1 =~ ^[1-9][0-9]{0,4}$ ]] && (( $1 <= 65535 ))
}

valid_https_url() {
    local pattern='^([[:alnum:]][[:alnum:].-]*|\[[[:xdigit:]:.]+\])(:([0-9]+))?(/[[:alnum:]._%+~/-]*)?$'
    [[ ${1#https://} =~ $pattern ]] || return 1
    [[ -z ${BASH_REMATCH[3]} ]] || valid_port "${BASH_REMATCH[3]}"
}

prompt_setting() {
    local name=$1 label=$2 validator=$3 default=${4:-} secret=${5:-false}
    local answer prompt="$label"
    [[ -z $default ]] || prompt+=" [$default]"
    while true; do
        if "$secret"; then
            read -rs -p "$prompt: " answer || die 'Installation cancelled before saving settings.'
            printf '\n' >&2
        else
            read -er -p "$prompt: " answer || die 'Installation cancelled before saving settings.'
        fi
        answer=${answer:-$default}
        if "$validator" "$answer"; then
            printf -v "$name" '%s' "$answer"
            return
        fi
        printf 'Invalid value for %s. Try again.\n' "$name" >&2
    done
}

prompt_https_url() {
    local name=$1 address
    prompt_setting "$name" "$2" valid_https_url "${3:-}"
    address=${!name}
    address=${address#https://}
    printf -v "$name" 'https://%s' "${address%/}"
}

valid_node_token() { [[ $1 =~ ^[a-zA-Z0-9_-]+$ ]]; }
valid_node_endpoint() { [[ $1 =~ ^[a-zA-Z0-9][a-zA-Z0-9.-]*$ ]]; }

detect_node_endpoint() {
    local address octet
    local -a octets
    local error='Could not detect an external IPv4 with ifconfig.me. Set -endpoint in the bootstrap command or --node-endpoint for swg.sh.'
    address=$(curl -q -4 -fsS --noproxy '*' --connect-timeout 5 --max-time 10 https://ifconfig.me/ip </dev/null) ||
        die "$error"
    [[ $address =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || die "$error"
    IFS=. read -r -a octets <<< "$address"
    for octet in "${octets[@]}"; do
        (( 10#$octet <= 255 )) || die "$error"
    done
    printf 'Detected external IPv4: %s\n' "$address" >&2
    printf '%s\n' "$address"
}

configure_installation() (
    local role=$1 PANEL_URL SUB_URL PANEL_PORT SUB_PORT NODE_TOKEN NODE_ENDPOINT settings
    if $token_stdin; then
        PANEL_URL=$node_panel_url
        NODE_TOKEN=$node_token
        NODE_ENDPOINT=$node_endpoint
        if [[ -z $NODE_ENDPOINT && -f .env && $(head -n 1 .env) == "$settings_header" &&
              $(sed -n "s/^PANEL_URL='\([^']*\)'$/\1/p" .env) == "$PANEL_URL" ]]; then
            NODE_ENDPOINT=$(sed -n "s/^NODE_ENDPOINT='\([^']*\)'$/\1/p" .env)
            valid_node_endpoint "$NODE_ENDPOINT" || NODE_ENDPOINT=
        fi
        if [[ -z $NODE_ENDPOINT ]]; then
            NODE_ENDPOINT=$(detect_node_endpoint)
        fi
    else
        [[ -t 0 ]] || die 'Initial setup requires a terminal or a node install command from the panel.'
        prompt_https_url PANEL_URL 'Public panel address (e.g. panel.example.org)'
    fi
    if [[ $role == panel ]]; then
        prompt_https_url SUB_URL 'Public subscription address' "${PANEL_URL#https://}/subs"
        while [[ $SUB_URL == "$PANEL_URL" ]]; do
            printf 'Use a separate URL for subscriptions.\n' >&2
            prompt_https_url SUB_URL 'Public subscription address' "${PANEL_URL#https://}/subs"
        done
        prompt_setting PANEL_PORT 'Local HTTP port for the panel' valid_port 6741
        prompt_setting SUB_PORT 'Local HTTP port for subscriptions' valid_port 8444
        while [[ $SUB_PORT == "$PANEL_PORT" ]]; do
            printf 'Use a separate local port for subscriptions.\n' >&2
            prompt_setting SUB_PORT 'Local HTTP port for subscriptions' valid_port
        done
    elif ! "$token_stdin"; then
        prompt_setting NODE_TOKEN 'Node token from the panel' valid_node_token '' true
        prompt_setting NODE_ENDPOINT 'Public hostname or IPv4 address of this node' valid_node_endpoint
    fi
    settings=$(mktemp .env.XXXXXX)
    trap 'rm -f -- "$settings"' EXIT
    {
        printf '%s\n' "$settings_header"
        printf "PANEL_URL='%s'\n" "$PANEL_URL"
        if [[ $role == panel ]]; then
            printf "SUB_URL='%s'\nPANEL_PORT=%s\nSUB_PORT=%s\n" "$SUB_URL" "$PANEL_PORT" "$SUB_PORT"
        else
            printf "NODE_TOKEN='%s'\nNODE_ENDPOINT='%s'\n" "$NODE_TOKEN" "$NODE_ENDPOINT"
        fi
    } > "$settings"
    mv -T -- "$settings" .env
)

install_packages() {
    DEBIAN_FRONTEND=noninteractive NEEDRESTART_MODE=l apt-get install -y --no-install-recommends "$@" </dev/null
}

require_ubuntu_root() {
    [[ $EUID == 0 ]] || die 'Run this script as root or with sudo.'
    . /etc/os-release
    [[ ${ID:-} == ubuntu && ${VERSION_ID:-0} =~ ^[0-9]+\.[0-9]+$ ]] &&
        ((10#${VERSION_ID%.*} > 24 || (10#${VERSION_ID%.*} == 24 && 10#${VERSION_ID#*.} >= 4))) ||
        die 'Ubuntu 24.04 LTS or newer is required.'
}

require_docker() {
    docker compose version >/dev/null 2>&1 || die 'Docker Engine and the Compose plugin are required.'
    docker info >/dev/null || die 'Docker Engine is unavailable.'
}

ensure_node_docker() {
    if ! command -v docker >/dev/null; then
        apt-get update </dev/null
        install_packages docker.io docker-compose-v2
        systemctl start docker
    elif ! docker compose version >/dev/null 2>&1; then
        local plugin=docker-compose-v2
        if [[ $(dpkg-query -W -f='${Status}' docker-ce-cli 2>/dev/null) == 'install ok installed' ]]; then
            plugin=docker-compose-plugin
        fi
        apt-get update </dev/null
        install_packages "$plugin"
    fi
}

patch_awg_source() (
    cd -- "$1"
    local fix="$source_dir/patches/amneziawg-udp-tunnel.patch"
    git apply --reverse --check "$fix" 2>/dev/null || git apply "$fix" ||
        die 'Could not apply the AmneziaWG UDP tunnel compatibility fix.'
)

install_awg_module() (
    local kernel tag=v3.1.20260906 dkms_version package trees flavour tmp
    kernel=$(uname -r)
    dkms_version=${tag#v}
    package="amneziawg/$dkms_version"
    trees="/usr/src/amneziawg-$dkms_version"

    if [[ -f $trees/dkms.conf ]]; then
        patch_awg_source "$trees"
    fi

    apt-get update </dev/null
    install_packages dkms build-essential kmod "linux-headers-$kernel"
    flavour=${kernel#*-}
    flavour=${flavour#*-}
    if apt-cache show "linux-headers-$flavour" >/dev/null 2>&1; then
        install_packages "linux-headers-$flavour"
    fi

    if [[ ! -f $trees/dkms.conf ]]; then
        tmp=$(mktemp -d)
        trap 'rm -rf -- "$tmp"' EXIT
        GIT_TERMINAL_PROMPT=0 git clone --quiet --depth 1 --branch "$tag" https://github.com/amnezia-vpn/amneziawg-linux-kernel-module.git "$tmp/source"
        sed -i "s/^PACKAGE_VERSION=.*/PACKAGE_VERSION=\"$dkms_version\"/" "$tmp/source/src/dkms.conf"
        make -C "$tmp/source/src" dkms-install DKMSDIR="$trees"
        patch_awg_source "$trees"
    fi
    if ! dkms install "$package" -k "$kernel"; then
        local build_log="/var/lib/dkms/$package/build/make.log"
        if [[ -f $build_log ]]; then
            tail -n 50 "$build_log" >&2
        fi
        die "AmneziaWG DKMS failed for $kernel. Check $build_log."
    fi
    modprobe wireguard
    modprobe amneziawg || die 'Could not load AmneziaWG. Check DKMS and whether Secure Boot trusts the module signing key.'
    printf 'wireguard\namneziawg\n' > /etc/modules-load.d/swg-node.conf
    sysctl -w net.ipv4.ip_forward=1
    printf 'net.ipv4.ip_forward = 1\n' > /etc/sysctl.d/90-swg-node.conf
)

ensure_awg_module() {
    if [[ ! -d /sys/module/amneziawg ]] && ! modprobe amneziawg; then
        printf 'Preparing AmneziaWG for running kernel %s.\n' "$(uname -r)" >&2
        install_awg_module
    fi
}

check_node_datapath() {
    docker run --rm --network none --cap-add NET_ADMIN --entrypoint /bin/sh \
        "ghcr.io/tesla-prep/swg-node:$1" -eu -c '
            trap "ip link del swg-awg-check 2>/dev/null || true" EXIT
            ip link add swg-awg-check type amneziawg
            umask 077
            { printf "[Interface]\nPrivateKey = %s\n" "$(awg genkey)"; /opt/swg-agent/swg-agent --awg-params 3.1; } > /tmp/awg-check.conf
            awg setconf swg-awg-check /tmp/awg-check.conf
            ip link del swg-awg-check
            ip link add swg-awg-check type wireguard
            wg show swg-awg-check
        ' || die "VPN datapath check failed for kernel $(uname -r). Check the error above on the node host."
}

if [[ ${1:-} == --help || ${1:-} == -h ]]; then
    echo "$usage"
    exit 0
fi

action=${1:-}
role=${2:-}
case "$action" in install|update) ;; *) die "$usage" ;; esac
case "$role" in panel|node) ;; *) die "$usage" ;; esac
dry_run=false
token_stdin=false
node_panel_url=
node_endpoint=
node_revision=
args=("$@")
shift 2
while (( $# )); do
    case "$1" in
        --dry-run) dry_run=true; shift; continue ;;
        --token-stdin) token_stdin=true; shift; continue ;;
        --panel-url) [[ -n ${2:-} ]] || die "$usage"; node_panel_url=$2 ;;
        --node-endpoint) [[ -n ${2:-} ]] || die "$usage"; node_endpoint=$2 ;;
        --revision) [[ -n ${2:-} ]] || die "$usage"; node_revision=$2 ;;
        *) die "$usage" ;;
    esac
    shift 2
done
if $token_stdin || [[ -n $node_panel_url || -n $node_endpoint ]]; then
    [[ $action == install && $role == node ]] && "$token_stdin" || die "$usage"
    valid_https_url "$node_panel_url" || die 'Set --panel-url to the public HTTPS URL of the panel.'
    [[ -z $node_endpoint ]] || valid_node_endpoint "$node_endpoint" ||
        die 'Set --node-endpoint to the public hostname or IPv4 address of the node.'
    node_panel_url=${node_panel_url#https://}
    node_panel_url=https://${node_panel_url%/}
fi
if [[ -n $node_revision ]]; then
    [[ $role == node && ( $action == update || $token_stdin == true ) ]] || die "$usage"
    [[ $node_revision =~ ^[a-f0-9]{40}$ ]] || die 'Invalid source revision.'
fi

source_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
if [[ ! -e "$source_dir/.git" || ! -f "$source_dir/docker/compose.$role.yml" ]]; then
    if ! command -v git >/dev/null; then
        ! "$dry_run" || die 'Git is required to resolve the source revision for a dry run.'
        require_ubuntu_root
        apt-get update </dev/null
        install_packages git ca-certificates
    fi
    checkout=$(mktemp -d)
    trap 'rm -rf -- "$checkout"' EXIT
    if [[ -n $node_revision ]]; then
        git -C "$checkout" init --quiet
        GIT_TERMINAL_PROMPT=0 git -C "$checkout" fetch --quiet --depth 1 "$source_repo" "$node_revision" </dev/null
        git -C "$checkout" checkout --quiet --detach FETCH_HEAD
    else
        GIT_TERMINAL_PROMPT=0 git clone --quiet --depth 1 --branch main "$source_repo" "$checkout" </dev/null
    fi
    bash "$checkout/swg.sh" "${args[@]}"
    exit
fi

install_dir="/opt/swg-$role"
revision=$(git -C "$source_dir" rev-parse HEAD)
[[ -z $node_revision || $node_revision == "$revision" ]] || die 'The checkout does not match --revision.'
image_tag="sha-${revision:0:7}"

installed_revision() {
    [[ -f "$install_dir/compose.yml" ]] ||
        die "No SWG $role installation at $install_dir. Start with swg.sh install $role."
    local current
    current=$(sed -n '1s/^# SWG revision: //p' "$install_dir/compose.yml")
    [[ $current =~ ^[a-f0-9]{40}$ ]] || die 'The Compose file was not generated by swg.sh.'
    printf '%s\n' "$current"
}

if $dry_run; then
    if [[ $action == update ]]; then
        current=$(installed_revision)
        echo "Would update SWG $role: $current -> $revision ($image_tag)."
        if [[ $role == node ]]; then
            echo 'Would prepare the AmneziaWG module if needed and verify the VPN datapath.'
        fi
    else
        echo "Would install SWG $role in $install_dir using images tagged $image_tag."
        if $token_stdin; then
            echo "Would save settings from the panel command to $install_dir/.env."
        else
            echo "Settings are entered in the terminal and saved to $install_dir/.env."
        fi
        if [[ $role == node ]]; then
            echo 'Would install the pinned AmneziaWG module via host DKMS and validate it from the node image.'
        fi
    fi
    exit 0
fi

require_ubuntu_root
node_token=
if $token_stdin; then
    set +x
    IFS= read -r node_token && valid_node_token "$node_token" || die 'Provide the node token on standard input.'
fi
if [[ $role == node ]]; then
    [[ -c /dev/net/tun ]] || die '/dev/net/tun is required by the SOCKS5 tunnel.'
fi
if [[ $role != node || $action != install ]]; then
    require_docker
fi

umask 077
if [[ $action == install ]]; then
    install -d -m 0700 "$install_dir"
else
    installed_revision >/dev/null
fi
cd -- "$install_dir"
exec 9>.deploy.lock
flock -n 9 || die "Another deployment is running in $install_dir."

if [[ $action == install ]]; then
    [[ ! -e compose.yml ]] || die "SWG $role is already installed. Run swg.sh update $role."
    if [[ $role == panel && ! -s data/etc/auth && ! -t 0 ]]; then
        die 'Initial panel setup requires a terminal to set the password.'
    fi
    if $token_stdin || [[ ! -f .env || $(head -n 1 .env) != "$settings_header" ]]; then
        configure_installation "$role"
    fi
elif [[ $(installed_revision) == "$revision" ]]; then
    if [[ $role == node ]]; then
        ensure_awg_module
        check_node_datapath "$image_tag"
    fi
    echo "SWG $role is already at $revision."
    exit 0
fi

if [[ $role == node && $action == install ]]; then
    ensure_node_docker
    require_docker
fi

candidate=$(mktemp .compose.XXXXXX)
trap 'rm -f -- "$candidate"' EXIT
{
    printf '# SWG revision: %s\n' "$revision"
    sed -e "s/SWG_REVISION/$image_tag/g" -e "s/SWG_COMMIT/$revision/g" "$source_dir/docker/compose.$role.yml"
} > "$candidate"

unset PANEL_URL SUB_URL PANEL_PORT SUB_PORT NODE_TOKEN NODE_ENDPOINT node_token
compose=(docker compose --ansi never --env-file .env -f "$candidate")
"${compose[@]}" config --quiet
for attempt in 1 2 3; do
    if "${compose[@]}" pull; then
        break
    fi
    if (( attempt == 3 )); then
        die "Could not pull swg-$role:$image_tag. Check that the image for revision $revision is published and accessible in GHCR."
    fi
    printf 'Image pull failed. Retrying…\n' >&2
    sleep "$((attempt * 3))"
done

if [[ $role == node ]]; then
    if [[ $action == install ]]; then
        install_awg_module
    else
        ensure_awg_module
    fi
    check_node_datapath "$image_tag"
else
    # swg-sub mounts data/lib read-only and needs this tmpfs mount point before startup.
    install -d -m 0700 data/lib/private
    if [[ ! -s data/etc/auth ]]; then
        [[ $action == install ]] || die 'Panel credentials are missing.'
        install -d -m 0700 data/etc data/lib data/lib/subs data/stats
        "${compose[@]}" run --rm --no-deps --entrypoint swg-passwd swg-panel
        [[ -s data/etc/auth ]] || die 'Panel credentials were not saved.'
    fi
fi

if ! "${compose[@]}" up -d --wait --wait-timeout 90; then
    if [[ $action == update ]]; then
        echo 'Deployment failed. Restoring the previous Compose specification.' >&2
        docker compose --ansi never --env-file .env -f compose.yml up -d --wait --wait-timeout 90 ||
            die "Rollback failed. Inspect Docker Compose logs in $install_dir."
    fi
    die "SWG $role failed to start. Inspect Docker Compose logs in $install_dir."
fi

mv -- "$candidate" compose.yml
echo "SWG $role is running revision $revision in $install_dir."
